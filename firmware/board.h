/* board.h : pin map v1 (2026-10-11) for the 301 Darts Scorer, STM32F103C8T6 Blue Pill.
 * Pin modes are set in CubeMX. These macros only name the pins the drivers use.
 * Status: written against the pin map. Not yet run on hardware. */
#ifndef BOARD_H
#define BOARD_H

#include "main.h" /* CubeMX header, pulls in stm32f1xx_hal.h */

/* LCD1602 through the 74HCT541, all on port B */
#define LCD_PORT        GPIOB
#define LCD_RS_PIN      GPIO_PIN_10
#define LCD_E_PIN       GPIO_PIN_11
#define LCD_D4_PIN      GPIO_PIN_12
#define LCD_D5_PIN      GPIO_PIN_13
#define LCD_D6_PIN      GPIO_PIN_14
#define LCD_D7_PIN      GPIO_PIN_15

/* Keypad rows: outputs, idle high */
#define KEY_ROW_PORT    GPIOA
#define KEY_R1_PIN      GPIO_PIN_4
#define KEY_R2_PIN      GPIO_PIN_5
#define KEY_R3_PIN      GPIO_PIN_7
#define KEY_R4_PIN      GPIO_PIN_15
/* Keypad columns: inputs, pull-up */
#define KEY_COL_PORT    GPIOB
#define KEY_C1_PIN      GPIO_PIN_0
#define KEY_C2_PIN      GPIO_PIN_1
#define KEY_C3_PIN      GPIO_PIN_3
#define KEY_C4_PIN      GPIO_PIN_4

/* Buttons: inputs, pull-up, active low */
#define BTN_PORT        GPIOB
#define BTN_UNDO_PIN    GPIO_PIN_5
#define BTN_NEW_PIN     GPIO_PIN_9

/* RGB LED, common cathode: high = on */
#define LED_PORT        GPIOA
#define LED_R_PIN       GPIO_PIN_8
#define LED_G_PIN       GPIO_PIN_9
#define LED_B_PIN       GPIO_PIN_10

/* ADC channels */
#define ADC_CH_POT      ADC_CHANNEL_0   /* PA0, brightness pot */

/* HT16K33 7-bit I2C addresses */
#define DISP1_ADDR      0x70U
#define DISP2_ADDR      0x71U           /* A0 jumper bridged */

/* Peripheral handles generated by CubeMX in main.c */
extern I2C_HandleTypeDef hi2c1;   /* PB6 SCL, PB7 SDA, 100 kHz */
extern TIM_HandleTypeDef htim3;   /* CH1 on PA6, buzzer */
extern TIM_HandleTypeDef htim4;   /* CH3 on PB8, speaker PWM */
extern ADC_HandleTypeDef hadc1;   /* IN0 */

/* Busy-wait delay. Guaranteed minimum at 72 MHz, not a precise interval. */
void Board_DelayUs(uint32_t us);

#endif /* BOARD_H */
